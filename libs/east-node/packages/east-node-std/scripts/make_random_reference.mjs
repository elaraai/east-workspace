// Writes test/random.reference.generated.ts: the first 1,000 values of
// random_uniform, random_range(1, 1000000) and random_normal after
// random_seed(s), from this package's own generator (XorShift128+ seeded by
// SplitMix64) and distributions, as East literals. test/random.spec.ts holds
// every runtime's std package — east-node-std here, east-py-std, east-c-std,
// which replay the exported suite — to them: a seeded program draws the same
// stream wherever it runs.
//
//   node scripts/make_random_reference.mjs      (after npm run build)
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dist = join(here, '..', 'dist', 'src', 'random');
const { default: XorShift128RNG } = await import(join(dist, 'xorshift128.js'));
const { default: uniformDist } = await import(join(dist, 'distributions', 'uniform.js'));
const { default: uniformIntDist } = await import(join(dist, 'distributions', 'uniform-int.js'));
const { default: normalDist } = await import(join(dist, 'distributions', 'normal.js'));

const N = 1000;
const draws = (seed, make) => {
    const rng = new XorShift128RNG(seed);
    const draw = make(rng);
    return Array.from({ length: N }, () => draw());
};
const uniform42 = draws(42n, (rng) => uniformDist(rng, 0, 1));
const range12345 = draws(12345n, (rng) => uniformIntDist(rng, 1n, 1000000n)).map((x) => BigInt(x));
const normal7 = draws(7n, (rng) => normalDist(rng, 0, 1));

const floats = (xs) => xs.map((x) => (Number.isInteger(x) ? `${x}.0` : String(x))).join(', ');
const out = `/**
 * Copyright (c) 2025 Elara AI Pty Ltd
 * Dual-licensed under AGPL-3.0 and commercial license. See LICENSE for details.
 */
// Generated by scripts/make_random_reference.mjs — do not edit. The first ${N}
// values of each seeded std stream, which random.spec.ts holds every runtime to.

/** random_uniform() × ${N} after random_seed(42). */
export const uniform42: number[] = [${floats(uniform42)}];

/** random_range(1, 1000000) × ${N} after random_seed(12345). */
export const range12345: bigint[] = [${range12345.map((x) => `${x}n`).join(', ')}];

/** random_normal() × ${N} after random_seed(7). */
export const normal7: number[] = [${floats(normal7)}];
`;
const target = join(here, '..', 'test', 'random.reference.generated.ts');
writeFileSync(target, out);
console.log(`wrote ${target}`);
