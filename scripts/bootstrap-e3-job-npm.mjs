#!/usr/bin/env node
// One-time bootstrap publisher for @elaraai/e3-job-win32-x64 — the Windows job
// launcher e3-core carries as an optionalDependency (libs/e3/native/e3-job).
//
// Why this exists
// ---------------
// As for scripts/bootstrap-east-c-npm.mjs: npm trusted publishing (OIDC from
// GitHub Actions) needs a package name to already exist on the registry,
// claimed by the org, before a trusted publisher can be configured for it. A
// new name cannot bootstrap through OIDC, so its first version is published by
// hand with a short-lived granular token (no --provenance), and release.yml
// publishes every version after that.
//
// It must run before the first real release that carries the launcher:
// publish-npm publishes the launcher before e3-core (whose optionalDependency
// pins it), and fails there until the name accepts trusted publishing.
//
// Inputs
// ------
// 1. An NPM_TOKEN env var: a granular access token with read+write on the
//    @elaraai scope, short TTL. Generated by the user on npmjs.com.
// 2. The directory holding the `e3-job-npm` artifact of a release.yml dry-run —
//    one elaraai-e3-job-win32-x64-<version>.tgz, flat or in e3-job-npm/.
//
// Procedure
// ---------
//   gh workflow run release.yml --ref main -f release_type=prerelease -f dry_run=true
//   gh run download <run-id> -D ./bootstrap-artifacts -n e3-job-npm
//   NPM_TOKEN=npm_xxx node scripts/bootstrap-e3-job-npm.mjs ./bootstrap-artifacts
//
// The version published is the tarball's own; a prerelease goes out under the
// `beta` dist-tag. Refuses to re-publish a version already on the registry, so
// a re-run is safe. --dry-run previews without touching the registry.
//
// After it succeeds:
// - Configure trusted publishing for @elaraai/e3-job-win32-x64 on npmjs.com
//   (Settings → Publishing access → Trusted publisher → GitHub Actions,
//   pointing at elaraai/east-workspace + release.yml).
// - Revoke the temporary NPM_TOKEN.

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { spawnSync } from 'node:child_process';
import { alreadyPublished } from './lib/already-published.mjs';

const NAME = '@elaraai/e3-job-win32-x64';
const TARBALL = /^elaraai-e3-job-win32-x64-(.+)\.tgz$/;

function usage(msg) {
  if (msg) console.error(msg);
  console.error('Usage: NPM_TOKEN=npm_xxx node scripts/bootstrap-e3-job-npm.mjs <artifacts-dir> [--dry-run]');
  console.error('  <artifacts-dir>  directory holding elaraai-e3-job-win32-x64-<version>.tgz (flat or in e3-job-npm/)');
  console.error('  --dry-run        publish in --dry-run mode (no registry mutation)');
  process.exit(2);
}

const args = process.argv.slice(2).filter(a => a !== '--dry-run');
const DRY_RUN = process.argv.includes('--dry-run');
if (args.length !== 1) usage('Expected exactly one positional argument: <artifacts-dir>.');
const artifactsDir = path.resolve(args[0]);
if (!fs.existsSync(artifactsDir)) usage(`Artifacts dir not found: ${artifactsDir}`);
if (!DRY_RUN && !process.env.NPM_TOKEN) usage('NPM_TOKEN env var is required (granular access token).');

const tarballs = [artifactsDir, path.join(artifactsDir, 'e3-job-npm')]
  .filter(dir => fs.existsSync(dir))
  .flatMap(dir => fs.readdirSync(dir).filter(f => TARBALL.test(f)).map(f => path.join(dir, f)));
if (tarballs.length !== 1) {
  console.error(tarballs.length === 0
    ? `No elaraai-e3-job-win32-x64-<version>.tgz in ${artifactsDir} (or its e3-job-npm/)`
    : `Expected one launcher tarball, found ${tarballs.length}:\n  ${tarballs.join('\n  ')}`);
  process.exit(1);
}
const tgz = tarballs[0];
const VERSION = path.basename(tgz).match(TARBALL)[1];
const DIST_TAG = VERSION.includes('-') ? 'beta' : 'latest';
console.log(`Bootstrapping ${NAME}@${VERSION} (tag ${DIST_TAG})${DRY_RUN ? ' [DRY RUN]' : ''}`);

// A temporary .npmrc carrying the token, for this invocation only (removed in
// finally{}), so the user's ~/.npmrc is never touched.
const npmrcDir = fs.mkdtempSync(path.join(os.tmpdir(), 'e3-job-bootstrap-'));
const npmrcPath = path.join(npmrcDir, '.npmrc');
let ok = false;
try {
  if (!DRY_RUN) {
    fs.writeFileSync(
      npmrcPath,
      `//registry.npmjs.org/:_authToken=${process.env.NPM_TOKEN}\nregistry=https://registry.npmjs.org/\n`,
      { mode: 0o600 },
    );
  }
  if (!DRY_RUN && alreadyPublished(NAME, VERSION)) {
    console.log(`  skip: ${NAME}@${VERSION} already on npm`);
    ok = true;
  } else {
    const publishArgs = ['publish', tgz, '--access', 'public', '--no-provenance', '--tag', DIST_TAG];
    if (DRY_RUN) publishArgs.push('--dry-run');
    console.log(`  publish: ${NAME}@${VERSION}${DRY_RUN ? ' (dry run)' : ''}  ←  ${tgz}`);
    const r = spawnSync('npm', publishArgs, {
      stdio: 'inherit',
      env: DRY_RUN ? process.env : { ...process.env, npm_config_userconfig: npmrcPath },
    });
    ok = r.status === 0;
  }
} finally {
  fs.rmSync(npmrcDir, { recursive: true, force: true });
}

if (!ok) {
  console.error(`  FAILED: ${NAME}@${VERSION}`);
  process.exit(1);
}
console.log(`\nDone${DRY_RUN ? ' (dry run)' : ''}.`);
if (!DRY_RUN) {
  console.log('\nNext steps:');
  console.log(`  1. On https://www.npmjs.com/package/${NAME}, configure trusted publishing:`);
  console.log('     Settings → Publishing access → Trusted publisher → GitHub Actions');
  console.log('     Repository: elaraai/east-workspace, Workflow: release.yml');
  console.log('  2. Revoke the temporary NPM_TOKEN you used here.');
  console.log('  3. Future releases publish it via release.yml with --provenance.');
}
