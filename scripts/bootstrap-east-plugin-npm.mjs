#!/usr/bin/env node
// One-time bootstrap publisher for @elaraai/east-plugin — the agent plugin
// runtime East's Claude Code and Codex plugins bundle, published for a plugin
// that builds on East's (#1234).
//
// Why this exists
// ---------------
// As for scripts/bootstrap-e3-job-npm.mjs: npm trusted publishing (OIDC from
// GitHub Actions) needs a package name to already exist on the registry,
// claimed by the org, before a trusted publisher can be configured for it. A
// new name cannot bootstrap through OIDC, so its first version is published by
// hand with a short-lived granular token (no --provenance), and release.yml
// publishes every version after that through scripts/publish-npm.mjs.
//
// It must run before the first real release that carries the package:
// publish-npm fails on @elaraai/east-plugin until the name accepts trusted
// publishing.
//
// Inputs
// ------
// 1. An NPM_TOKEN env var: a granular access token with read+write on the
//    @elaraai scope, short TTL. Generated by the user on npmjs.com.
// 2. A built package: make -C libs/east-plugin build.
//
// Procedure
// ---------
//   make -C libs/east-plugin build
//   NPM_TOKEN=npm_xxx node scripts/bootstrap-east-plugin-npm.mjs
//
// The version published is the package's own, packed with `pnpm pack` (which
// writes each workspace dependency as the version it is); a prerelease goes
// out under the `beta` dist-tag. Refuses to re-publish a version already on
// the registry, so a re-run is safe. --dry-run previews without touching the
// registry.
//
// After it succeeds:
// - Configure trusted publishing for @elaraai/east-plugin on npmjs.com
//   (Settings → Publishing access → Trusted publisher → GitHub Actions,
//   pointing at elaraai/east-workspace + release.yml).
// - Revoke the temporary NPM_TOKEN.

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { alreadyPublished } from './lib/already-published.mjs';
import { missingEntryPoints } from './lib/entry-points.mjs';

const NAME = '@elaraai/east-plugin';
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkgDir = path.join(repoRoot, 'libs', 'east-plugin');

const DRY_RUN = process.argv.includes('--dry-run');
if (process.argv.slice(2).some(a => a !== '--dry-run')) {
  console.error('Usage: NPM_TOKEN=npm_xxx node scripts/bootstrap-east-plugin-npm.mjs [--dry-run]');
  process.exit(2);
}
if (!DRY_RUN && !process.env.NPM_TOKEN) {
  console.error('NPM_TOKEN env var is required (granular access token).');
  process.exit(2);
}

const pkg = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));
if (pkg.name !== NAME || pkg.private === true) {
  console.error(`${pkgDir} is not the publishable ${NAME}`);
  process.exit(1);
}
const missing = missingEntryPoints(pkgDir, pkg);
if (missing.length > 0) {
  console.error(`NOT BUILT: ${NAME} lacks the entry points its manifest names: ${missing.join(', ')} — run make -C libs/east-plugin build`);
  process.exit(1);
}
const VERSION = pkg.version;
const DIST_TAG = VERSION.includes('-') ? 'beta' : 'latest';
console.log(`Bootstrapping ${NAME}@${VERSION} (tag ${DIST_TAG})${DRY_RUN ? ' [DRY RUN]' : ''}`);

// The tarball and a temporary .npmrc carrying the token, for this invocation
// only (removed in finally{}), so the user's ~/.npmrc is never touched.
const work = fs.mkdtempSync(path.join(os.tmpdir(), 'east-plugin-bootstrap-'));
const npmrcPath = path.join(work, '.npmrc');
let ok = false;
try {
  const packed = spawnSync('pnpm', ['pack', '--pack-destination', work], {
    cwd: pkgDir,
    stdio: ['ignore', 'pipe', 'inherit'],
    encoding: 'utf8',
    shell: process.platform === 'win32',
  });
  const tarballs = fs.readdirSync(work).filter(f => f.endsWith('.tgz'));
  if (packed.status !== 0 || tarballs.length !== 1) {
    throw new Error(`pnpm pack did not produce one tarball (status ${packed.status}): ${tarballs.join(', ')}`);
  }
  const tgz = path.join(work, tarballs[0]);

  if (!DRY_RUN) {
    fs.writeFileSync(
      npmrcPath,
      `//registry.npmjs.org/:_authToken=${process.env.NPM_TOKEN}\nregistry=https://registry.npmjs.org/\n`,
      { mode: 0o600 },
    );
  }
  if (!DRY_RUN && alreadyPublished(NAME, VERSION)) {
    console.log(`  skip: ${NAME}@${VERSION} already on npm`);
    ok = true;
  } else {
    const publishArgs = ['publish', tgz, '--access', 'public', '--no-provenance', '--tag', DIST_TAG];
    if (DRY_RUN) publishArgs.push('--dry-run');
    console.log(`  publish: ${NAME}@${VERSION}${DRY_RUN ? ' (dry run)' : ''}  ←  ${path.basename(tgz)}`);
    const r = spawnSync('npm', publishArgs, {
      stdio: 'inherit',
      env: DRY_RUN ? process.env : { ...process.env, npm_config_userconfig: npmrcPath },
      shell: process.platform === 'win32',
    });
    ok = r.status === 0;
  }
} finally {
  fs.rmSync(work, { recursive: true, force: true });
}

if (!ok) {
  console.error(`  FAILED: ${NAME}@${VERSION}`);
  process.exit(1);
}
console.log(`\nDone${DRY_RUN ? ' (dry run)' : ''}.`);
if (!DRY_RUN) {
  console.log('\nNext steps:');
  console.log(`  1. On https://www.npmjs.com/package/${NAME}, configure trusted publishing:`);
  console.log('     Settings → Publishing access → Trusted publisher → GitHub Actions');
  console.log('     Repository: elaraai/east-workspace, Workflow: release.yml');
  console.log('  2. Revoke the temporary NPM_TOKEN you used here.');
  console.log('  3. Future releases publish it via release.yml with --provenance.');
}
