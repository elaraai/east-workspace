#!/usr/bin/env node
// One-time bootstrap publisher for @elaraai/e3-rack — the rack protocol, local
// hub and task delegation package e3-cli depends on.
//
// Why this exists
// ---------------
// As for scripts/bootstrap-east-plugin-npm.mjs: npm trusted publishing (OIDC
// from GitHub Actions) needs a package name to already exist on the registry,
// claimed by the org, before a trusted publisher can be configured for it. A
// new name cannot bootstrap through OIDC, so its first version is published by
// hand with a short-lived granular token (no --provenance), and release.yml
// publishes every version after that through scripts/publish-npm.mjs.
//
// Unlike that script, this one publishes a placeholder, not the package as the
// tree holds it: e3-rack needs the e3-core of the release that first carries
// it, so a copy at the tree's current version would install against an e3-core
// without the exports it imports. The placeholder holds a README and the
// licence only, at 0.0.0-bootstrap.0 under the `bootstrap` dist-tag; the
// release then publishes the real package at its version, as `latest`.
//
// It must run before the first real release that carries the package:
// publish-npm fails on @elaraai/e3-rack until the name accepts trusted
// publishing, and holds back e3-cli, which depends on it.
//
// Inputs
// ------
// An NPM_TOKEN env var: a granular access token with read+write on the
// @elaraai scope, short TTL. Generated by the user on npmjs.com.
//
// Procedure
// ---------
//   NPM_TOKEN=npm_xxx node scripts/bootstrap-e3-rack-npm.mjs
//
// Refuses to re-publish the placeholder once it is on the registry, so a
// re-run is safe. --dry-run previews without touching the registry.
//
// After it succeeds:
// - Configure trusted publishing for @elaraai/e3-rack on npmjs.com
//   (Settings → Publishing access → Trusted publisher → GitHub Actions,
//   pointing at elaraai/east-workspace + release.yml).
// - Revoke the temporary NPM_TOKEN.

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { alreadyPublished } from './lib/already-published.mjs';

const NAME = '@elaraai/e3-rack';
const VERSION = '0.0.0-bootstrap.0';
const DIST_TAG = 'bootstrap';
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkgDir = path.join(repoRoot, 'libs', 'e3', 'packages', 'e3-rack');

const DRY_RUN = process.argv.includes('--dry-run');
if (process.argv.slice(2).some(a => a !== '--dry-run')) {
  console.error('Usage: NPM_TOKEN=npm_xxx node scripts/bootstrap-e3-rack-npm.mjs [--dry-run]');
  process.exit(2);
}
if (!DRY_RUN && !process.env.NPM_TOKEN) {
  console.error('NPM_TOKEN env var is required (granular access token).');
  process.exit(2);
}

const real = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));
if (real.name !== NAME || real.private === true) {
  console.error(`${pkgDir} is not the publishable ${NAME}`);
  process.exit(1);
}
console.log(`Bootstrapping ${NAME}@${VERSION} (tag ${DIST_TAG}), a placeholder that claims the name${DRY_RUN ? ' [DRY RUN]' : ''}`);

// The placeholder and a temporary .npmrc carrying the token, for this
// invocation only (removed in finally{}), so the user's ~/.npmrc is never touched.
const work = fs.mkdtempSync(path.join(os.tmpdir(), 'e3-rack-bootstrap-'));
const placeholder = path.join(work, 'package');
const npmrcPath = path.join(work, '.npmrc');
let ok = false;
try {
  fs.mkdirSync(placeholder);
  fs.writeFileSync(path.join(placeholder, 'package.json'), `${JSON.stringify({
    name: NAME,
    version: VERSION,
    description: `${real.description} — this version only reserves the name; install the release matching your e3`,
    license: real.license,
    repository: real.repository,
    files: ['README.md', 'LICENSE.md'],
  }, null, 2)}\n`);
  fs.writeFileSync(path.join(placeholder, 'README.md'),
    `# ${NAME}\n\nThis version only reserves the package name, so that releases can be published through npm trusted publishing. It contains no code.\n\nInstall the version that matches your e3 release, as \`@elaraai/e3-cli\` does.\n`);
  fs.copyFileSync(path.join(pkgDir, 'LICENSE.md'), path.join(placeholder, 'LICENSE.md'));

  if (!DRY_RUN) {
    fs.writeFileSync(
      npmrcPath,
      `//registry.npmjs.org/:_authToken=${process.env.NPM_TOKEN}\nregistry=https://registry.npmjs.org/\n`,
      { mode: 0o600 },
    );
  }
  if (!DRY_RUN && alreadyPublished(NAME, VERSION)) {
    console.log(`  skip: ${NAME}@${VERSION} already on npm`);
    ok = true;
  } else {
    const publishArgs = ['publish', placeholder, '--access', 'public', '--no-provenance', '--tag', DIST_TAG];
    if (DRY_RUN) publishArgs.push('--dry-run');
    console.log(`  publish: ${NAME}@${VERSION}${DRY_RUN ? ' (dry run)' : ''}`);
    const r = spawnSync('npm', publishArgs, {
      stdio: 'inherit',
      env: DRY_RUN ? process.env : { ...process.env, npm_config_userconfig: npmrcPath },
      shell: process.platform === 'win32',
    });
    ok = r.status === 0;
  }
} finally {
  fs.rmSync(work, { recursive: true, force: true });
}

if (!ok) {
  console.error(`  FAILED: ${NAME}@${VERSION}`);
  process.exit(1);
}
console.log(`\nDone${DRY_RUN ? ' (dry run)' : ''}.`);
if (!DRY_RUN) {
  console.log('\nNext steps:');
  console.log(`  1. On https://www.npmjs.com/package/${NAME}, configure trusted publishing:`);
  console.log('     Settings → Publishing access → Trusted publisher → GitHub Actions');
  console.log('     Repository: elaraai/east-workspace, Workflow: release.yml');
  console.log('  2. Revoke the temporary NPM_TOKEN you used here.');
  console.log('  3. The next release publishes the real package via release.yml with --provenance.');
}
