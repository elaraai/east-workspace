#!/usr/bin/env node
// One-time bootstrap publisher for the @elaraai/east-c-cli launcher + the
// 5 per-platform packages.
//
// Why this exists
// ---------------
// npm trusted publishing (OIDC from GitHub Actions) requires the package
// name to ALREADY exist on the registry and be claimed by your org before
// the trusted publisher config can be applied. New names can't bootstrap
// via OIDC. This script does the manual first-publish with a short-lived
// granular token (no --provenance), so the user can then go configure
// trusted publishing on npmjs.com and let release.yml take over for all
// subsequent versions.
//
// Inputs
// ------
// 1. An NPM_TOKEN env var: a granular access token scoped to the 6 names,
//    with read+write, short TTL. Generated by the user on npmjs.com.
// 2. A directory of c-npm-* artifacts downloaded from a release.yml dry-run.
//    Each artifact contains one `elaraai-east-c-cli-<target>-<version>.tgz` ready to
//    publish. See the "Bootstrap" section of
//    libs/east-c/docs/npm-runner-distribution.md for the full procedure.
//
// What it does
// ------------
// 1. Reads the root version. Computes the npm dist-tag (`beta` for
//    prereleases, `latest` for stable).
// 2. For each of the 5 per-platform tarballs, runs
//    `npm publish <tgz> --access public --no-provenance --tag <dist-tag>`.
// 3. Packs and publishes the launcher from libs/east-c/packages/east-c-cli.
//    Order matters: platform packages must exist before the launcher
//    publishes, because the launcher's optionalDependencies pin them at
//    the same version.
// 4. Refuses to overwrite an existing name+version: this is idempotent and
//    safe to re-run after a partial failure.
//
// Usage
// -----
//   NPM_TOKEN=npm_xxx node scripts/bootstrap-east-c-npm.mjs <artifacts-dir> [--dry-run]
//
// After it succeeds:
// - Configure trusted publishing for each of the 6 new package names in the
//   npm UI (Settings → Publishing access → Trusted publisher → GitHub Actions,
//   pointing at elaraai/east-workspace + release.yml).
// - Revoke the temporary NPM_TOKEN.
// - Run release.yml normally; future versions publish with provenance.

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { alreadyPublished } from './lib/already-published.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');

const TARGETS = ['linux-x64', 'linux-arm64', 'darwin-arm64', 'darwin-x64', 'win32-x64'];

function usage(msg) {
  if (msg) console.error(msg);
  console.error('Usage: NPM_TOKEN=npm_xxx node scripts/bootstrap-east-c-npm.mjs <artifacts-dir> [--dry-run]');
  console.error('  <artifacts-dir>  directory containing c-npm-<target>/elaraai-east-c-cli-<target>-<version>.tgz');
  console.error('  --dry-run        pack/publish in --dry-run mode (no registry mutation)');
  process.exit(2);
}

const args = process.argv.slice(2).filter(a => a !== '--dry-run');
const DRY_RUN = process.argv.includes('--dry-run');
if (args.length !== 1) usage('Expected exactly one positional argument: <artifacts-dir>.');
const artifactsDir = path.resolve(args[0]);
if (!fs.existsSync(artifactsDir)) usage(`Artifacts dir not found: ${artifactsDir}`);

if (!DRY_RUN && !process.env.NPM_TOKEN) usage('NPM_TOKEN env var is required (granular access token).');

const rootPkg = JSON.parse(fs.readFileSync(path.join(repoRoot, 'package.json'), 'utf8'));
const VERSION = rootPkg.version;
const DIST_TAG = VERSION.includes('-') ? 'beta' : 'latest';
console.log(`Bootstrapping @elaraai/east-c-cli + 5 platform packages at version ${VERSION} (tag ${DIST_TAG})${DRY_RUN ? ' [DRY RUN]' : ''}`);

// Stage a temporary .npmrc carrying the auth token, scoped to this invocation
// only (deleted in finally{}). Avoids modifying the user's ~/.npmrc.
const npmrcDir = fs.mkdtempSync(path.join(os.tmpdir(), 'east-c-bootstrap-'));
const npmrcPath = path.join(npmrcDir, '.npmrc');
if (!DRY_RUN) {
  fs.writeFileSync(
    npmrcPath,
    `//registry.npmjs.org/:_authToken=${process.env.NPM_TOKEN}\nregistry=https://registry.npmjs.org/\n`,
    { mode: 0o600 },
  );
}

function npmEnv() {
  return DRY_RUN ? process.env : { ...process.env, npm_config_userconfig: npmrcPath };
}

function findTarball(target) {
  // Artifacts layout per release.yml's actions/upload-artifact step: when
  // `merge-multiple: true` is used the .tgz files land flat in the dir;
  // otherwise each artifact lands in its own subdir. Look in both.
  // npm pack folds the scope into the filename (elaraai- prefix).
  const flat = path.join(artifactsDir, `elaraai-east-c-cli-${target}-${VERSION}.tgz`);
  if (fs.existsSync(flat)) return flat;
  const nested = path.join(artifactsDir, `c-npm-${target}`, `elaraai-east-c-cli-${target}-${VERSION}.tgz`);
  if (fs.existsSync(nested)) return nested;
  return null;
}

function publishTarball(name, tgz) {
  if (!DRY_RUN && alreadyPublished(name, VERSION)) {
    console.log(`  skip: ${name}@${VERSION} already on npm`);
    return true;
  }
  const args = ['publish', tgz, '--access', 'public', '--no-provenance', '--tag', DIST_TAG];
  if (DRY_RUN) args.push('--dry-run');
  console.log(`  publish: ${name}@${VERSION}${DRY_RUN ? ' (dry run)' : ''}  ←  ${path.relative(repoRoot, tgz)}`);
  const r = spawnSync('npm', args, { stdio: 'inherit', env: npmEnv() });
  return r.status === 0;
}

function publishDir(name, dir) {
  if (!DRY_RUN && alreadyPublished(name, VERSION)) {
    console.log(`  skip: ${name}@${VERSION} already on npm`);
    return true;
  }
  const args = ['publish', '--access', 'public', '--no-provenance', '--tag', DIST_TAG, '--no-git-checks'];
  if (DRY_RUN) args.push('--dry-run');
  console.log(`  publish: ${name}@${VERSION}${DRY_RUN ? ' (dry run)' : ''}  ←  ${path.relative(repoRoot, dir)}`);
  // Use pnpm publish for consistency with publish-npm.mjs (handles workspace deps).
  const r = spawnSync('pnpm', args, { cwd: dir, stdio: 'inherit', env: npmEnv() });
  return r.status === 0;
}

function injectPlatformDeps(launcherDir) {
  const r = spawnSync(
    'node',
    [
      path.join(repoRoot, 'scripts/inject-east-c-platform-deps.mjs'),
      '--version', VERSION,
      '--file', path.join(launcherDir, 'package.json'),
    ],
    { stdio: 'inherit' },
  );
  if (r.status !== 0) throw new Error('inject-east-c-platform-deps.mjs failed');
}

let failed = 0;
try {
  // Pre-flight: every per-platform tarball must exist.
  const missing = [];
  for (const target of TARGETS) {
    if (!findTarball(target)) missing.push(target);
  }
  if (missing.length > 0) {
    console.error(`Missing per-platform tarball(s): ${missing.join(', ')}`);
    console.error(`Expected in ${artifactsDir} as either elaraai-east-c-cli-<target>-${VERSION}.tgz or c-npm-<target>/elaraai-east-c-cli-<target>-${VERSION}.tgz`);
    process.exit(1);
  }

  // 1. Per-platform packages first (the launcher's optionalDependencies
  //    reference them by exact version, so they must exist on the registry
  //    before the launcher install is resolvable).
  console.log('\n-- Per-platform packages --');
  for (const target of TARGETS) {
    const tgz = findTarball(target);
    const name = `@elaraai/east-c-cli-${target}`;
    if (!publishTarball(name, tgz)) { console.error(`  FAILED: ${name}`); failed++; }
  }

  // 2. Launcher package. The committed launcher package.json has NO
  //    optionalDependencies (keeps pnpm-lock.yaml clean — see
  //    inject-east-c-platform-deps.mjs for the rationale). Inject them here
  //    so the published tarball pulls the right per-platform package on
  //    end-user `npm install`. We revert the file in `finally` below.
  console.log('\n-- Launcher --');
  const launcherDir = path.join(repoRoot, 'libs/east-c/packages/east-c-cli');
  injectPlatformDeps(launcherDir);
  if (!publishDir('@elaraai/east-c-cli', launcherDir)) { console.error('  FAILED: launcher'); failed++; }
} finally {
  if (!DRY_RUN) {
    try { fs.rmSync(npmrcDir, { recursive: true, force: true }); } catch { /* ignore */ }
  }
  // Revert the launcher's package.json so the working tree returns to its
  // committed state (no optionalDependencies). Best-effort — only attempts
  // if git is available.
  try {
    spawnSync('git', ['checkout', '--', 'libs/east-c/packages/east-c-cli/package.json'], {
      cwd: repoRoot,
      stdio: 'ignore',
    });
  } catch { /* ignore */ }
}

console.log(`\nDone${DRY_RUN ? ' (dry run)' : ''}: ${failed} failed.`);
if (!DRY_RUN && failed === 0) {
  console.log('\nNext steps:');
  console.log('  1. Visit each new package on https://www.npmjs.com/ and configure trusted publishing:');
  console.log('     Settings → Publishing access → Trusted publisher → GitHub Actions');
  console.log('     Repository: elaraai/east-workspace, Workflow: release.yml');
  console.log('  2. Revoke the temporary NPM_TOKEN you used here.');
  console.log('  3. Future releases will publish via release.yml with --provenance.');
}
process.exit(failed > 0 ? 1 : 0);
