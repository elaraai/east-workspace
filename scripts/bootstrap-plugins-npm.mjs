#!/usr/bin/env node
// One-time bootstrap publisher for East's agent plugins —
// @elaraai/east-claude-plugin and @elaraai/east-codex-plugin — the assembled
// plugin directories a Claude Code or Codex marketplace installs as npm
// packages (#1309).
//
// Why this exists
// ---------------
// As for scripts/bootstrap-east-plugin-npm.mjs: npm trusted publishing (OIDC
// from GitHub Actions) needs a package name to already exist on the registry,
// claimed by the org, before a trusted publisher can be configured for it. A
// new name cannot bootstrap through OIDC, so its first version is published by
// hand with a short-lived granular token (no --provenance), and release.yml
// publishes every version after that through scripts/publish-plugins.mjs.
//
// It must run before the first real release that carries the packages:
// publish-plugins fails on each name until it accepts trusted publishing.
//
// Inputs
// ------
// 1. An NPM_TOKEN env var: a granular access token with read+write on the
//    @elaraai scope, short TTL. Generated by the user on npmjs.com.
// 2. The assembled plugins: make -C libs/east-plugin package (after the
//    workspace is built: make build does both).
//
// Procedure
// ---------
//   make -C libs/east-plugin package
//   NPM_TOKEN=npm_xxx node scripts/bootstrap-plugins-npm.mjs
//
// The version published is each plugin's own (plugin.json's, the lockstep
// version), which must be the version the tree is on (the root
// package.json's, what the root marketplaces pin); an assembly on another
// version, or one missing a part, is refused as the release's publish
// refuses it. A prerelease goes out under the `beta` dist-tag. Refuses to
// re-publish a version already on the registry, so a re-run is safe.
// --dry-run previews without touching the registry.
//
// After it succeeds:
// - Configure trusted publishing for BOTH names on npmjs.com (Settings →
//   Publishing access → Trusted publisher → GitHub Actions, pointing at
//   elaraai/east-workspace + release.yml).
// - Revoke the temporary NPM_TOKEN.
// - The catalog (elaraai/plugins) lists each package at its next render.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { alreadyPublished } from './lib/already-published.mjs';
import { PLUGIN_DIRS, missingParts } from './lib/plugin-packages.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// The version the tree is on: what the root marketplaces pin, and so the
// only version worth claiming a name with (a published version is immutable).
const canonical = JSON.parse(fs.readFileSync(path.join(repoRoot, 'package.json'), 'utf8')).version;

const DRY_RUN = process.argv.includes('--dry-run');
if (process.argv.slice(2).some((a) => a !== '--dry-run')) {
  console.error('Usage: NPM_TOKEN=npm_xxx node scripts/bootstrap-plugins-npm.mjs [--dry-run]');
  process.exit(2);
}
if (!DRY_RUN && !process.env.NPM_TOKEN) {
  console.error('NPM_TOKEN env var is required (granular access token).');
  process.exit(2);
}

// A temporary .npmrc carrying the token, for this invocation only (removed in
// finally{}), so the user's ~/.npmrc is never touched.
const work = fs.mkdtempSync(path.join(os.tmpdir(), 'east-plugins-bootstrap-'));
const npmrcPath = path.join(work, '.npmrc');
let failed = 0;
try {
  if (!DRY_RUN) {
    fs.writeFileSync(
      npmrcPath,
      `//registry.npmjs.org/:_authToken=${process.env.NPM_TOKEN}\nregistry=https://registry.npmjs.org/\n`,
      { mode: 0o600 },
    );
  }
  for (const rel of PLUGIN_DIRS) {
    const dir = path.join(repoRoot, rel);
    const manifestPath = path.join(dir, 'package.json');
    if (!fs.existsSync(manifestPath)) {
      console.error(`NOT ASSEMBLED: ${rel} — run make -C libs/east-plugin package`);
      failed++;
      continue;
    }
    const pkg = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
    const tag = pkg.version.includes('-') ? 'beta' : 'latest';
    console.log(`Bootstrapping ${pkg.name}@${pkg.version} (tag ${tag})${DRY_RUN ? ' [DRY RUN]' : ''}`);
    // The same refusals as the release's publish: a stale or partial local
    // assembly must not become the permanent first version of a name.
    if (pkg.version !== canonical) {
      console.error(`  STALE: ${rel} is ${pkg.name}@${pkg.version}, the tree is on ${canonical} — run make -C libs/east-plugin package`);
      failed++;
      continue;
    }
    const missing = missingParts(dir, pkg);
    if (missing.length > 0) {
      console.error(`  INCOMPLETE: ${pkg.name}@${pkg.version} lacks ${missing.join(', ')}`);
      failed++;
      continue;
    }
    if (!DRY_RUN && alreadyPublished(pkg.name, pkg.version)) {
      console.log(`  skip: ${pkg.name}@${pkg.version} already on npm`);
      continue;
    }
    const args = ['publish', dir, '--access', 'public', '--no-provenance', '--ignore-scripts', '--tag', tag];
    if (DRY_RUN) args.push('--dry-run');
    console.log(`  publish: ${pkg.name}@${pkg.version}${DRY_RUN ? ' (dry run)' : ''}`);
    const r = spawnSync('npm', args, {
      cwd: repoRoot,
      stdio: 'inherit',
      env: DRY_RUN ? process.env : { ...process.env, npm_config_userconfig: npmrcPath },
      shell: process.platform === 'win32',
    });
    if (r.status !== 0) {
      console.error(`  FAILED: ${pkg.name}@${pkg.version}`);
      failed++;
    }
  }
} finally {
  fs.rmSync(work, { recursive: true, force: true });
}

if (failed > 0) process.exit(1);
console.log(`\nDone${DRY_RUN ? ' (dry run)' : ''}.`);
if (!DRY_RUN) {
  console.log('\nNext steps:');
  console.log('  1. On npmjs.com, configure trusted publishing for each package:');
  console.log('     https://www.npmjs.com/package/@elaraai/east-claude-plugin and');
  console.log('     https://www.npmjs.com/package/@elaraai/east-codex-plugin →');
  console.log('     Settings → Publishing access → Trusted publisher → GitHub Actions');
  console.log('     Repository: elaraai/east-workspace, Workflow: release.yml');
  console.log('  2. Revoke the temporary NPM_TOKEN you used here.');
  console.log('  3. Future releases publish them via release.yml with --provenance;');
  console.log('     elaraai/plugins lists them at its next render.');
}
